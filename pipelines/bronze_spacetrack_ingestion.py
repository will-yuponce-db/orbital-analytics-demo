@dlt.table(
    name="bronze_cdm_data",
    comment=(
        "Raw Conjunction Data Messages (CDMs) from Space-Track.org. CDMs are generated "
        "by the Combined Space Operations Center (CSpOC) when two objects are predicted "
        "to violate screening thresholds. Each CDM contains the Time of Closest Approach "
        "(TCA), miss distance, collision probability (Pc), and state/covariance data for "
        "both objects. CDMs follow the CCSDS 508.0-B-1 standard."
    ),
    table_properties={
        "quality": "bronze",
        "pipelines.autoOptimize.managed": "true",
        "domain": "space_domain_awareness",
    },
)
@dlt.expect("valid_cdm_id", "CDM_ID IS NOT NULL")
@dlt.expect("valid_tca", "TCA IS NOT NULL")
@dlt.expect("valid_sat1_id", "SAT_1_ID IS NOT NULL AND SAT_1_ID > 0")
@dlt.expect("valid_sat2_id", "SAT_2_ID IS NOT NULL AND SAT_2_ID > 0")
@dlt.expect("valid_miss_distance", "MIN_RNG IS NOT NULL AND MIN_RNG >= 0")
@dlt.expect("valid_collision_probability", "PC IS NOT NULL AND PC >= 0")
def bronze_cdm_data():
    """
    Ingest raw CDM data from Space-Track volume using Auto Loader.

    CDMs arrive in batches as conjunction screenings are updated by CSpOC.
    Typical operational cadence produces updated CDMs every 8 hours for
    high-interest events, with emergency reportable conjunctions generating
    out-of-cycle updates.

    Data quality expectations enforce:
    - Valid CDM identifiers for traceability
    - Non-null TCA (Time of Closest Approach) for timeline analysis
    - Valid NORAD IDs for both primary and secondary objects
    - Non-negative miss distance and collision probability values
    """
    return (
        spark.readStream.format("cloudFiles")
        .option("cloudFiles.format", "json")
        .option("cloudFiles.inferColumnTypes", "true")
        .option("cloudFiles.schemaLocation", f"{RAW_CDM_PATH}_checkpoint/schema")
        .schema(CDM_SCHEMA)
        .load(RAW_CDM_PATH)
        .withColumn("_ingestion_timestamp", F.current_timestamp())
        .withColumn("_source_file", F.input_file_name())
        .withColumn(
            "_tca_parsed",
            F.to_timestamp(F.col("TCA"), "yyyy-MM-dd HH:mm:ss.SSS"),
        )
    )
