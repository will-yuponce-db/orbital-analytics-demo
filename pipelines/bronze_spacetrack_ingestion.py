@dlt.table(
    name="bronze_gp_data",
    comment=(
        "Raw General Perturbations (GP) orbital element sets from Space-Track.org. "
        "Each record is an SGP4-compatible TLE observation for a cataloged resident "
        "space object (RSO) in the US Space Surveillance Network. Sourced from the "
        "18th Space Defense Squadron (18 SDS) catalog."
    ),
    table_properties={
        "quality": "bronze",
        "pipelines.autoOptimize.managed": "true",
        "domain": "space_domain_awareness",
    },
)
@dlt.expect("valid_norad_id", "NORAD_CAT_ID IS NOT NULL AND NORAD_CAT_ID > 0")
@dlt.expect("valid_epoch", "EPOCH IS NOT NULL")
@dlt.expect("valid_object_name", "OBJECT_NAME IS NOT NULL")
@dlt.expect("valid_mean_motion", "MEAN_MOTION IS NOT NULL AND MEAN_MOTION > 0")
@dlt.expect("has_tle_line1", "TLE_LINE1 IS NOT NULL")
@dlt.expect("has_tle_line2", "TLE_LINE2 IS NOT NULL")
def bronze_gp_data():
    """
    Ingest raw GP data from Space-Track volume using Auto Loader.

    Auto Loader incrementally processes new files as they land in the volume,
    supporting both batch and streaming ingestion. This is critical for
    operational SDA where catalog updates arrive on 8-12 hour cycles from
    the 18th SDS.

    Data quality expectations enforce:
    - Valid NORAD Catalog IDs (positive integers assigned by USSPACECOM)
    - Non-null epoch timestamps (observation time of the element set)
    - Presence of object names and TLE lines for SGP4 propagation
    """
    return (
        spark.readStream.format("cloudFiles")
        .option("cloudFiles.format", "json")
        .option("cloudFiles.inferColumnTypes", "true")
        .option("cloudFiles.schemaLocation", f"{RAW_GP_PATH}_checkpoint/schema")
        .schema(GP_SCHEMA)
        .load(RAW_GP_PATH)
        .withColumn("_ingestion_timestamp", F.current_timestamp())
        .withColumn("_source_file", F.input_file_name())
        .withColumn(
            "_epoch_parsed",
            F.to_timestamp(F.col("EPOCH"), "yyyy-MM-dd'T'HH:mm:ss.SSSSSS"),
        )
    )


