# MAGIC
# MAGIC CDMs are generated by CSpOC when two cataloged objects are predicted to pass
# MAGIC within a screening threshold (typically 1 km radial, 25 km in-track/cross-track
# MAGIC for LEO). CDMs follow the CCSDS 508.0-B-1 standard and include:
# MAGIC
# MAGIC - Time of Closest Approach (TCA)
# MAGIC - Miss distance at TCA
# MAGIC - Collision probability (Pc) computed via the Foster method or similar
# MAGIC - Covariance matrices for both objects
# MAGIC
# MAGIC CDMs are the basis for COLA decision-making. Operators typically action on
# MAGIC Pc > 1e-4 (amber threshold) and Pc > 1e-2 (red threshold) per JSpOC standards.

# COMMAND ----------

